"""scripts/gradle_sbom.py reads Gradle's verification metadata. The digests here are placeholders."""

import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import gradle_sbom  # noqa: E402

XML = """<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
   <configuration><verify-metadata>true</verify-metadata><verify-signatures>false</verify-signatures></configuration>
   <components>
      <component group="junit" name="junit" version="4.13.2">
         <artifact name="junit-4.13.2.jar"><sha256 value="{a}" origin="Generated by Gradle"/></artifact>
         <artifact name="junit-4.13.2.pom"><sha256 value="{b}" origin="Generated by Gradle"/></artifact>
      </component>
      <component group="androidx.compose" name="compose-bom" version="2024.12.01">
         <artifact name="compose-bom-2024.12.01.pom"><sha256 value="{b}" origin="Generated by Gradle"/></artifact>
      </component>
   </components>
</verification-metadata>
""".format(a="1" * 64, b="2" * 64)


class GradleSbom(unittest.TestCase):
    def test_one_component_per_module_with_its_binary_hashes(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "verification-metadata.xml"
            path.write_text(XML)
            listed = gradle_sbom.components(path)
        self.assertEqual([c["purl"] for c in listed], ["pkg:maven/androidx.compose/compose-bom@2024.12.01", "pkg:maven/junit/junit@4.13.2"])
        self.assertNotIn("hashes", listed[0])
        self.assertEqual(listed[1]["hashes"], [{"alg": "SHA-256", "content": "1" * 64}])


if __name__ == "__main__":
    unittest.main()
